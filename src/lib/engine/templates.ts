function navMarkup(spec: SiteSpec): string {
  return spec.navItems
    .map(
      (item, index) =>
        `        <a href="#${item.toLowerCase().replace(/\s+/g, "-")}"${index === 0 ? ' class="is-active"' : ""}>${item}</a>`,
    )
    .join("\n");
}

function featuresMarkup(spec: SiteSpec): string {
  return spec.features
    .map(
      (feature) => `        <article class="card feature">
          <h3>${escapeHtml(feature.title)}</h3>
          <p>${escapeHtml(feature.body)}</p>
        </article>`,
    )
    .join("\n");
}

function heroMarkup(spec: SiteSpec): string {
  const ctas: Record<string, [string, string]> = {
    tasks: ["Add your first task", "How it works"],
    dashboard: ["View the numbers", "Export data"],
    store: ["Browse products", "View cart"],
    blog: ["Start reading", "About"],
    booking: ["Book now", "Contact us"],
    portfolio: ["See my work", "Get in touch"],
    landing: ["Get started", "Learn more"],
  };
  const [primary, secondary] = ctas[spec.archetype];
  return `      <div class="hero-copy">
        <p class="eyebrow">${escapeHtml(spec.name)}</p>
        <h1>${escapeHtml(spec.tagline)}</h1>
        <p class="lede">${escapeHtml(spec.description || "A fast, responsive site generated by MUGIWARA.")}</p>
        <div class="cta-row">
          <button class="btn btn-primary" data-scroll="#app">${primary}</button>
          <button class="btn btn-ghost" data-scroll="#features">${secondary}</button>
        </div>
      </div>`;
}

