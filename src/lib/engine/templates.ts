function tasksScript(spec: SiteSpec): string {
  return `  var KEY = 'mugiwara-tasks-' + ${JSON.stringify(spec.name)};
  var list = read();
  var form = el('form', { className: 'row' });
  var input = el('input', { type: 'text', placeholder: 'What needs doing?', 'aria-label': 'New task' });
  input.style.flex = '1';
  form.appendChild(input);
  form.appendChild(el('button', { className: 'btn btn-primary', type: 'submit', textContent: 'Add task' }));
  form.addEventListener('submit', function (e) {
    e.preventDefault();
    var value = input.value.trim();
    if (!value) return;
    list.push({ id: String(Date.now()), title: value, done: false });
    input.value = '';
    save(); render();
  });
  root.appendChild(form);
  var listEl = el('ul', { className: 'list' });
  root.appendChild(listEl);
  render();

  function render() {
    listEl.innerHTML = '';
    if (list.length === 0) {
      root.querySelector('.empty') || root.appendChild(el('div', { className: 'empty', textContent: 'Nothing here yet — add your first task above.' }));
      return;
    }
    var empty = root.querySelector('.empty');
    if (empty) empty.remove();
    list.forEach(function (task) {
      var li = el('li', { className: task.done ? 'done' : '' });
      var box = el('input', { type: 'checkbox', 'aria-label': 'Mark complete' });
      box.checked = task.done;
      box.addEventListener('change', function () { task.done = box.checked; save(); render(); });
      var label = el('span', { className: 'label', textContent: task.title });
      var del = el('button', { className: 'btn btn-danger btn-sm', type: 'button', textContent: 'Remove' });
      del.addEventListener('click', function () {
        list = list.filter(function (t) { return t.id !== task.id; });
        save(); render();
      });
      li.appendChild(box); li.appendChild(label); li.appendChild(del);
      listEl.appendChild(li);
    });
  }

  function save() { try { localStorage.setItem(KEY, JSON.stringify(list)); } catch (e) {} }
  function read() { try { return JSON.parse(localStorage.getItem(KEY) || '[]'); } catch (e) { return []; } }`;
}

function dashboardScript(_spec: SiteSpec): string {
  return `  var months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun'];
  var values = [42, 58, 51, 74, 66, 89];
  var total = values.reduce(function (a, b) { return a + b; }, 0);
  var peak = Math.max.apply(null, values);

  var metrics = el('div', { className: 'metric-grid' });
  [
    { key: 'Total this half-year', value: total },
    { key: 'Best month', value: peak },
    { key: 'Average', value: Math.round(total / values.length) }
  ].forEach(function (m) {
    var card = el('div', { className: 'metric' });
    card.appendChild(el('div', { className: 'value', textContent: String(m.value) }));
    card.appendChild(el('div', { className: 'key', textContent: m.key }));
    metrics.appendChild(card);
  });
  root.appendChild(metrics);

  var bars = el('div', { className: 'bars' });
  values.forEach(function (v, i) {
    var bar = el('div', { className: 'bar' });
    bar.style.height = Math.round((v / peak) * 100) + '%';
    bar.appendChild(el('span', { textContent: months[i] }));
    bar.title = months[i] + ': ' + v;
    bars.appendChild(bar);
  });
  root.appendChild(bars);

  var exportBtn = el('button', { className: 'btn btn-ghost btn-sm', type: 'button', textContent: 'Export CSV' });
  exportBtn.style.marginTop = '38px';
  exportBtn.addEventListener('click', function () {
    var csv = 'month,value\\n' + months.map(function (m, i) { return m + ',' + values[i]; }).join('\\n');
    var url = URL.createObjectURL(new Blob([csv], { type: 'text/csv' }));
    var a = document.createElement('a');
    a.href = url; a.download = 'report.csv'; a.click();
    URL.revokeObjectURL(url);
    toast('Report exported.');
  });
  root.appendChild(exportBtn);`;
}

