export function buildJs(spec: SiteSpec): string {
  return `/* ${spec.name} — generated by MUGIWARA. Plain, dependency-free JavaScript. */
(function () {
  'use strict';

  /* -- tiny DOM helpers -------------------------------------------------- */
  function el(tag, props) {
    var node = document.createElement(tag);
    props = props || {};
    Object.keys(props).forEach(function (key) {
      if (key === 'className' || key === 'textContent' || key === 'type' || key === 'value') {
        node[key] = props[key];
      } else {
        node.setAttribute(key, props[key]);
      }
    });
    return node;
  }

  function toast(message) {
    var existing = document.querySelector('.toast');
    if (existing) existing.remove();
    var node = el('div', { className: 'toast', role: 'status', textContent: message });
    document.body.appendChild(node);
    setTimeout(function () { node.remove(); }, 2600);
  }

  /* -- page chrome ------------------------------------------------------- */
  var yearEl = document.getElementById('year');
  if (yearEl) yearEl.textContent = String(new Date().getFullYear());

  Array.prototype.forEach.call(document.querySelectorAll('[data-scroll]'), function (btn) {
    btn.addEventListener('click', function () {
      var target = document.querySelector(btn.getAttribute('data-scroll'));
      if (target) target.scrollIntoView({ behavior: 'smooth', block: 'start' });
    });
  });

  var navCta = document.getElementById('nav-cta');
  if (navCta) {
    navCta.addEventListener('click', function () {
      var app = document.getElementById('app');
      if (app) app.scrollIntoView({ behavior: 'smooth', block: 'start' });
    });
  }

  var sections = document.querySelectorAll('main section[id]');
  var navLinks = document.querySelectorAll('.site-nav a');
  if ('IntersectionObserver' in window && sections.length) {
    var observer = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (!entry.isIntersecting) return;
        Array.prototype.forEach.call(navLinks, function (link) {
          link.classList.toggle('is-active', link.getAttribute('href') === '#' + entry.target.id);
        });
      });
    }, { rootMargin: '-45% 0px -50% 0px' });
    Array.prototype.forEach.call(sections, function (s) { observer.observe(s); });
  }

  /* -- archetype behaviour ---------------------------------------------- */
  var root = document.getElementById('app-root');
  if (!root) return;

${SCRIPT_BY_ARCHETYPE[spec.archetype](spec)}
})();
`;
}

