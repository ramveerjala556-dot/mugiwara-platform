/** Build the complete static site for a spec. */
export function buildStaticSite(spec: SiteSpec): GeneratedFile[] {
  return [
    { path: "index.html", language: "html", content: buildHtml(spec) },
    { path: "styles.css", language: "css", content: buildCss(spec) },
    { path: "app.js", language: "javascript", content: buildJs(spec) },
    { path: "README.md", language: "markdown", content: buildReadme(spec) },
  ];
}

function escapeHtml(input: string): string {
  return input
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
