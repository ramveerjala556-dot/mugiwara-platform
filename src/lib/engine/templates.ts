    { id: 'p1', name: 'Signature Blend', price: 12 },
    { id: 'p2', name: 'Seasonal Roast', price: 15 },
    { id: 'p3', name: 'Decaf Reserve', price: 11 },
    { id: 'p4', name: 'Gift Box', price: 28 }
